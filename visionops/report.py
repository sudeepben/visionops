"""Build reports/RESULTS.md from files the pipeline actually produced, and inject it
into README.md and docs/MODEL_CARD.md between <!-- RESULTS:START --> / <!-- RESULTS:END -->.
Nothing here is typed by hand: sections whose inputs do not exist say "not run yet".

    python -m visionops.report
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

from .config import DATASET_DIR, REPORTS_DIR, ROOT

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _load(p: Path):
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8")) if p.suffix == ".json" else pd.read_csv(p)


def _f(x, nd=3):
    return "-" if x is None or (isinstance(x, float) and x != x) else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def _table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(_f(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def build() -> str:
    out = ["_Auto-generated by `python -m visionops.report` from files in `reports/`._", ""]

    dv, man = _load(REPORTS_DIR / "data_validation.json"), _load(DATASET_DIR / "split_manifest.json")
    out.append("### Dataset")
    if dv:
        out.append(f"Classes ({dv['num_classes']}): {', '.join(dv['names'])}")
        rows = [{"split": k, "images": v["images"], "boxes": v["instances"],
                 "label issues": sum(v["issues"].values())} for k, v in dv["splits"].items()]
        out.append(_table(pd.DataFrame(rows)))
        if man:
            out.append(f"\nSplit method: {man['method']}")
        for w in dv.get("warnings", []):
            out.append(f"- Warning: {w}")
    else:
        out.append("Not run yet.")

    m = _load(REPORTS_DIR / "baseline" / "metrics.json")
    run = _load(REPORTS_DIR / "runs" / "baseline.json")
    out += ["", "### Baseline model - held-out test set"]
    if m:
        u, op = m.get("ultralytics", {}), m["operating_point"]
        if run:
            env = run.get("env", {})
            out.append(f"Model `{run['model']}`, {run['train_args']['epochs']} epochs, imgsz {run['train_args']['imgsz']}, "
                       f"seed {run['train_args']['seed']}, trained in {run['train_minutes']} min on "
                       f"{env.get('gpu', 'CPU')} (torch {env.get('torch')}, ultralytics {env.get('ultralytics')}).")
        out.append(_table(pd.DataFrame([{
            "mAP@50": u.get("map50"), "mAP@50-95": u.get("map50_95"), "precision": u.get("precision"),
            "recall": u.get("recall"), f"P @conf{op['conf_thr']}": op["precision"],
            f"R @conf{op['conf_thr']}": op["recall"], f"F1 @conf{op['conf_thr']}": op["f1"]}])))
        pc = _load(REPORTS_DIR / "baseline" / "per_class.csv")
        if pc is not None:
            keep = [c for c in ["class", "instances", "precision", "recall", "map50", "map50_95", "op_f1"] if c in pc]
            out += ["", "Per class:", _table(pc[keep])]
        c = m["counts"]
        out += ["", f"Test images: {c['images']} ({c['images_fully_correct']} with no FP/FN at the operating point), "
                    f"GT boxes: {c['gt_boxes']}.",
                f"False positives by type: {c['fp_by_subtype']}. False negatives by type: {c['fn_by_subtype']}.",
                f"Low-confidence true positives: {c['low_confidence_tp']}. "
                f"High-confidence disagreements flagged for label review: {c['annotation_suspicions'] or 0}."]
    else:
        out.append("Not run yet.")

    q = _load(REPORTS_DIR / "review" / "review_queue.csv")
    out += ["", "### Review queue (training set)"]
    if q is not None:
        out.append(f"{len(q)} training images have at least one review signal; "
                   f"{int(q['possible_annotation_issue'].sum())} include a possible annotation issue. "
                   "These are review priorities, not confirmed label errors.")
    else:
        out.append("Not run yet.")

    comp = _load(REPORTS_DIR / "experiments" / "comparison.csv")
    out += ["", "### Curation experiment (same untouched test set)"]
    if comp is not None and len(comp):
        cols = [c for c in ["run", "epochs", "train_images", "removed_images", "test_map50", "test_map50_95",
                            "op_f1"] if c in comp]
        out.append(_table(comp[cols]))
        if comp.groupby("variant").size().min() < 2:
            out.append("\nSingle seed per variant: differences of this size may be run-to-run noise.")
    else:
        out.append("Not run yet.")

    ox = _load(REPORTS_DIR / "onnx_consistency.json")
    out += ["", "### ONNX export consistency"]
    if ox:
        out.append(f"{ox['images']} test images, conf {ox['conf']}: {ox['matched_boxes']} of "
                   f"{max(ox['boxes_pytorch'], ox['boxes_onnx'])} boxes matched (IoU>=0.5, same class), "
                   f"mean IoU {_f(ox['mean_iou_matched'])}, max |conf diff| {_f(ox['max_abs_conf_diff'])}.")
    else:
        out.append("Not run yet.")
    return "\n".join(out) + "\n"


def inject(path: Path, text: str) -> None:
    if not path.exists():
        return
    s = path.read_text(encoding="utf-8")
    if START in s and END in s:
        s = re.sub(re.escape(START) + r".*?" + re.escape(END), f"{START}\n{text}{END}", s, flags=re.S)
        path.write_text(s, encoding="utf-8")


def main() -> None:
    text = build()
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "RESULTS.md").write_text(text, encoding="utf-8")
    for p in (ROOT / "README.md", ROOT / "docs" / "MODEL_CARD.md"):
        inject(p, text)
    print(text)


if __name__ == "__main__":
    main()
